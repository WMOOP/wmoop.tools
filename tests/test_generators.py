"""Generators: emit idiomatic, correct and deterministic code from a WorldModel."""

from __future__ import annotations

import filecmp
import importlib

import pytest
from conftest import import_generated

from wmoop_tools.compile import ModelError, validate
from wmoop_tools.generators.csharp_gen import generate_csharp
from wmoop_tools.generators.python_gen import generate_python
from wmoop_tools.loader import load_model


def _files(root):
    return sorted(str(p.relative_to(root)) for p in root.rglob("*") if p.is_file())


def _assert_identical(a, b):
    assert _files(a) == _files(b)
    for rel in _files(a):
        assert filecmp.cmp(a / rel, b / rel, shallow=False), f"non-deterministic: {rel}"


def _model(tmp_path, yaml_text: str):
    """A one-module model ``wmoop.cite`` written from ``yaml_text``."""
    folder = tmp_path / "model" / "cite"
    folder.mkdir(parents=True)
    (folder / "cite.wml.yaml").write_text("module:\n  id: wmoop.cite\n  version: 1.0.0\n" + yaml_text, encoding="utf-8")
    return validate(load_model(str(tmp_path / "model")))


# --- Python binding ------------------------------------------------------------


def test_python_layout_is_a_namespace_package(world_model, tmp_path):
    generate_python(world_model, str(tmp_path))
    pkg = tmp_path / "wmoop"
    assert sorted(p.name for p in pkg.iterdir()) == ["_kernel.py", "animals.py", "base.py", "core.py", "society.py"]
    assert not (pkg / "__init__.py").exists()
    assert (pkg / "animals.py").read_text(encoding="utf-8").startswith("# <auto-generated>")


def test_python_inheritance_chain(generated_python):
    a = generated_python.animals
    assert issubclass(a.Person, a.Mammal)
    assert issubclass(a.Mammal, a.Animal)
    assert issubclass(a.Animal, generated_python.base.Thing)
    assert issubclass(a.Person, generated_python.core.Entity)


def test_python_abstract_cannot_be_instantiated(generated_python):
    with pytest.raises(TypeError, match="abstract"):
        generated_python.animals.Animal("wm:x", "x", label="x")


def test_python_properties_are_snake_case_and_keyword_only(generated_python):
    a = generated_python.animals
    person = a.Person("wm:p", "Ada", label="person", leg_count=2, full_name="Ada Lovelace", sex="female")
    assert (person.full_name, person.leg_count, person.label, person.name) == ("Ada Lovelace", 2, "person", "Ada")
    assert person.sex is a.Sex.female
    assert person.date_of_birth is None  # absent, not a made-up value
    with pytest.raises(TypeError):
        a.Person("wm:p", "Ada", "person")  # properties are keyword-only


def test_python_required_slots_are_enforced(generated_python):
    a = generated_python.animals
    with pytest.raises(TypeError):
        a.Person("wm:p", "Ada", label="person")  # full_name missing
    with pytest.raises(ValueError, match="full_name is required"):
        a.Person("wm:p", "Ada", label="person", full_name=None)


def test_python_role_attached_by_composition(generated_python):
    a, s = generated_python.animals, generated_python.society
    person = a.Person("wm:p", "Ada", label="person", full_name="Ada")
    citizen = s.Citizen(citizen_id="RO-1")
    assert person.add_role(citizen) is citizen
    assert person.has_role(s.Citizen)
    assert person.get_role(s.Citizen).citizen_id == "RO-1"
    assert citizen.subject is person
    assert str(citizen.role_type) == "wmoop.society/Citizen"
    assert not issubclass(s.Citizen, a.Person)  # a role is not a subclass of its subject


def test_python_role_refuses_a_subject_of_the_wrong_type(generated_python):
    class Rock(generated_python.base.Thing):  # hand-written, so instantiable
        pass

    with pytest.raises(TypeError, match=r"played by wmoop\.animals/Person"):
        Rock("wm:r", "rock", label="rock").add_role(generated_python.society.Citizen(citizen_id="RO-1"))


def test_python_mixin_adds_behaviour_and_is_inherited(world_model, isolated_imports):
    out, ext = isolated_imports / "gen", isolated_imports / "ext"
    generate_python(world_model, str(out))
    (ext / "wmoop_ext").mkdir(parents=True)
    (ext / "wmoop_ext" / "animals.py").write_text(
        "class AnimalExt:\n"
        "    def describe(self):\n"
        "        return f'{self.name} has {self.leg_count} legs'\n"
        "\n"
        "class PersonExt:\n"
        "    def describe(self):\n"
        "        return 'person ' + super().describe()\n",
        encoding="utf-8",
    )
    a = import_generated(out, ext).animals
    person = a.Person("wm:p", "Ada", label="person", full_name="Ada", leg_count=2)
    assert person.describe() == "person Ada has 2 legs"
    assert issubclass(a.Person, importlib.import_module("wmoop_ext.animals").PersonExt)


def test_python_extension_import_errors_surface(world_model, isolated_imports):
    out, ext = isolated_imports / "gen", isolated_imports / "ext"
    generate_python(world_model, str(out))
    (ext / "wmoop_ext").mkdir(parents=True)
    (ext / "wmoop_ext" / "animals.py").write_text("import no_such_module_wmoop\n", encoding="utf-8")
    with pytest.raises(ModuleNotFoundError, match="no_such_module_wmoop"):
        import_generated(out, ext)


def test_python_keywords_and_kernel_names_are_escaped(tmp_path, isolated_imports):
    wm = _model(
        tmp_path,
        "concepts:\n"
        "  - id: wmoop.cite/Citation\n"
        "    kind: concrete\n"
        "    properties:\n"
        "      - {id: wmoop.cite/Citation#from, name: from, type: string}\n"
        "      - {id: wmoop.cite/Citation#name, name: name, type: string}\n",
    )
    out = isolated_imports / "gen"
    generate_python(wm, str(out))
    cite = import_generated(out, modules=("cite",)).cite
    c = cite.Citation("wm:c", "c", from_="2020", name_="Title")
    assert (c.from_, c.name_, c.name) == ("2020", "Title", "c")


def test_python_unknown_type_is_a_model_error(tmp_path):
    wm = _model(
        tmp_path,
        "concepts:\n"
        "  - id: wmoop.cite/Citation\n"
        "    properties:\n"
        "      - {id: wmoop.cite/Citation#page, name: page, type: wmoop.cite/Nope}\n",
    )
    with pytest.raises(ModelError, match=r"cannot map type 'wmoop\.cite/Nope'"):
        generate_python(wm, str(tmp_path / "out"))


def test_python_generation_is_deterministic(world_model, tmp_path):
    d1, d2 = tmp_path / "a", tmp_path / "b"
    generate_python(world_model, str(d1))
    generate_python(world_model, str(d2))
    _assert_identical(d1, d2)


