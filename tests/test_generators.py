def test_csharp_one_project_per_module_and_a_solution(world_model, tmp_path):
    generate_csharp(world_model, str(tmp_path))
    projects = ["Wmoop.Animals", "Wmoop.Base", "Wmoop.Core", "Wmoop.Society"]
    assert sorted(p.name for p in tmp_path.iterdir() if p.is_dir()) == projects
    for name in projects:
        assert (tmp_path / name / f"{name}.csproj").is_file()
    assert (tmp_path / "Wmoop.Core" / "Kernel.Gen.cs").is_file()
    assert sorted(p.name for p in (tmp_path / "Wmoop.Animals").glob("*.Gen.cs")) == [
        "Animal.Gen.cs",
        "Mammal.Gen.cs",
        "Person.Gen.cs",
        "Sex.Gen.cs",
    ]
    sln = (tmp_path / "Wmoop.Generated.sln").read_text(encoding="utf-8")
    assert all(f'"{name}\\{name}.csproj"' in sln for name in projects)


def test_csharp_project_references_follow_the_module_graph(world_model, tmp_path):
    generate_csharp(world_model, str(tmp_path))
    society = (tmp_path / "Wmoop.Society" / "Wmoop.Society.csproj").read_text(encoding="utf-8")
    assert '<ProjectReference Include="../Wmoop.Core/Wmoop.Core.csproj" />' in society
    assert '<ProjectReference Include="../Wmoop.Animals/Wmoop.Animals.csproj" />' in society
    assert "Wmoop.Base.csproj" not in society  # only direct dependencies
    assert '<Compile Include="$(WmoopSourceRoot)/Wmoop.Society/**/*.cs"' in society  # the hand-written half


def test_csharp_types_are_partial_with_init_properties(world_model, tmp_path):
    generate_csharp(world_model, str(tmp_path))
    person = (tmp_path / "Wmoop.Animals" / "Person.Gen.cs").read_text(encoding="utf-8")
    assert person.startswith("// <auto-generated>")
    assert "namespace Wmoop.Animals;" in person
    assert "public partial class Person : Mammal" in person
    assert "public required string FullName { get; init; }" in person
    assert "public Sex? Sex { get; init; }" in person  # optional: absence is not a default value
    assert "public DateOnly? DateOfBirth { get; init; }" in person
    animal = (tmp_path / "Wmoop.Animals" / "Animal.Gen.cs").read_text(encoding="utf-8")
    assert "public abstract partial class Animal : global::Wmoop.Base.Thing" in animal
    assert "public long? LegCount { get; init; }" in animal
    assert "public global::Wmoop.Core.Quantity? Mass { get; init; }" in animal
    citizen = (tmp_path / "Wmoop.Society" / "Citizen.Gen.cs").read_text(encoding="utf-8")
    assert "public partial class Citizen : global::Wmoop.Core.Role" in citizen
    assert 'public const string WmPlayedBy = "wmoop.animals/Person";' in citizen


def test_csharp_names_never_clash(tmp_path):
    wm = _model(
        tmp_path,
        "enumerations:\n"
        "  - id: wmoop.cite/Kind\n"
        "    values: [{id: default}, {id: book}]\n"
        "concepts:\n"
        "  - id: wmoop.cite/Title\n"
        "    kind: concrete\n"
        "    properties:\n"
        "      - {id: wmoop.cite/Title#title, name: title, type: string}\n"
        "      - {id: wmoop.cite/Title#name, name: name, type: string}\n",
    )
    out = tmp_path / "cs"
    generate_csharp(wm, str(out))
    title = (out / "Wmoop.Cite" / "Title.Gen.cs").read_text(encoding="utf-8")
    assert "public string? TitleValue { get; init; }" in title  # a member cannot share its class's name
    assert "public string? NameValue { get; init; }" in title  # nor hide Entity.Name
    assert "    @default," in (out / "Wmoop.Cite" / "Kind.Gen.cs").read_text(encoding="utf-8")


